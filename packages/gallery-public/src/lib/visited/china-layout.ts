/**
 * Original schematic province mosaic for the local China footprint design review.
 * This is display geometry only: it must never be used to determine photo locations.
 * Shared mainland boundaries use a rectangular/trapezoid grid. Coastlines and
 * relative areas are intentionally simplified; small regions are enlarged for use.
 */
export type ChinaRegion = {
  id: string;
  name: string;
  fullName: string;
  path: string;
  label: readonly [number, number];
  lines?: readonly string[];
  fontSize?: number;
  vertices: readonly (readonly [number, number])[];
};

const polygon = (
  id: string,
  name: string,
  fullName: string,
  vertices: readonly (readonly [number, number])[],
  label: readonly [number, number],
  fontSize = 18,
  lines?: readonly string[],
): ChinaRegion => ({
  id: `CN-${id}`,
  name,
  fullName,
  vertices,
  label,
  fontSize,
  ...(lines ? { lines } : {}),
  path:
    vertices.map(([x, y], index) => `${index ? 'L' : 'M'}${x},${y}`).join(' ') +
    ' Z',
});

